def _md_table(df: pd.DataFrame, floatfmt: str = "{:.2f}") -> str:
    if df is None or df.empty:
        return "_none_\n"
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, float):
                cells.append("–" if pd.isna(v) else floatfmt.format(v))
            elif v is None or (not isinstance(v, (list, tuple, dict)) and pd.isna(v)):
                cells.append("–")
            else:
                cells.append(str(v).replace("|", "/").replace("\n", " "))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def market_rules_markdown() -> str:
    reg = default_registry()
    rows = pd.DataFrame(reg.audit_rows())
    lines = ["# Market Rules Registry", "",
             "_Generated from `auction_alpha/rules/registry_data/*.yaml` - edit the YAML, then run "
             "`python -m auction_alpha docs`._", "",
             f"Registry content hash: `{reg.version_hash()}`", "",
             "Status legend: **verified_official** = read on an official exchange page in this project (URL and "
             "access date recorded); **secondary_unverified** = from secondary knowledge or a page read only via "
             "summary - confirm before use; **assumption** = modelling choice (e.g. negotiated commission); "
             "**unknown** = value not established.", "",
             "`effective_from` blank means the start date is unknown. A lookup for a date before "
             "`verified_as_of` on such a rule is flagged **historically_assumed** and counted in every backtest's "
             "rule-usage report - current rules are never silently assumed to have applied historically.", ""]
    st = rows.groupby(["market", "status"]).size().unstack(fill_value=0)
    lines += ["## Verification summary", "", _md_table(st.reset_index(), "{:.0f}"), ""]
    for m, mr in reg.markets.items():
        lines += [f"## {mr.exchange_name} ({m})", "", f"Timezone `{mr.timezone}`, currency {mr.currency}, "
                  f"registry version `{mr.registry_version}`.", "", "### Sources", ""]
        for s in mr.sources.values():
            ok = "loaded" if s.fetched_ok else "NOT loaded"
            lines.append(f"- `{s.id}`: [{s.title}]({s.url}) - accessed {s.accessed or 'n/a'} ({ok}). {s.notes}")
        lines += ["", "### Rules", "", "| key | status | effective from | effective to | verified as of | value | notes |",
                  "|---|---|---|---|---|---|---|"]
        for key in mr.keys():
            for v in mr.rules[key]:
                val = json.dumps(v.value, default=str) if v.value is not None else "–"
                if len(val) > 160:
                    val = val[:157] + "..."
                lines.append(f"| `{key}` | {v.status} | {v.effective_from or ''} | {v.effective_to or ''} | "
                             f"{v.verified_as_of or ''} | `{val.replace('|', '/')}` | {v.notes.replace('|', '/')} |")
        lines.append("")
    return "\n".join(lines)


def strategies_markdown() -> str:
    lines = ["# Strategy Specifications", "",
             "_Generated from the `StrategySpec` of each class in `auction_alpha/strategies/`._", "",
             "Every strategy has two modes: a **diagnostic** study (mode A, may use forward labels, labelled NOT "
             "EXECUTABLE) and a **causal backtest** (mode B, orders generated only after their inputs were "
             "available, filled by the execution simulator).", ""]
    for cls in STRATEGIES.values():
        lines.append(cls.spec.as_markdown())
    return "\n".join(lines)


def data_feasibility_markdown(av: pd.DataFrame, datasets: list[dict]) -> str:
    reg = default_registry()
    rows = pd.DataFrame(reg.audit_rows())
    w = matrix_wide(av).reset_index().rename(columns={"data": "dataset"})
    sup = strategy_support(av, STRATEGIES)
    sw = sup.pivot(index="strategy", columns="market", values="support").reset_index()
    has_real = (av["status"] == "real").any()
    lines = ["# Data Feasibility Report", "",
             "_Generated by `python -m auction_alpha data-audit`._", "",
             "## Bottom line", "",
             ("Real market data **is** present in the store for the cells marked `real`." if has_real else
              "**No real market data is available in this environment.** Every dataset in the store is synthetic. "
              "Consequently no strategy can be evaluated empirically yet: empirical profitability of closing-auction "
              "strategies on SET, SGX or HKEX has **not** been established by this project."), "",
             "## Datasets in the store", "", _md_table(pd.DataFrame(datasets)), "",
             "## Availability matrix (best status across datasets)", "",
             "`real` = present in a non-synthetic dataset; `synthetic_only` = engineering tests only; `missing`; "
             "`not_applicable` by exchange rule.", "", _md_table(w), "",
             "## Strategy support matrix", "",
             "`supported_real` requires every required dataset to be real. `synthetic_only` strategies run end-to-end "
             "on synthetic data for engineering validation only. `unsupported` = a required dataset is missing; the "
             "strategy is NOT simulated with invented data.", "", _md_table(sw), "",
             "## Rule verification status", "", _md_table(rows.groupby(["market", "status"]).size().unstack(fill_value=0).reset_index(), "{:.0f}"),
             "", "## Potential real data sources (not accessed; licensing required)", ""]
    for m, s in POTENTIAL_SOURCES.items():
        lines.append(f"- **{m}**: {s}")
    lines += ["", "See `docs/UNRESOLVED_DATA_REQUIREMENTS.md` for the prioritised list.", ""]
    return "\n".join(lines)


VERDICT_TEXT = {
    "executable_edge_after_costs": "supported (executable after costs)",
    "statistical_anomaly_not_executable": "anomaly present but not executable after costs",
    "no_robust_effect": "rejected (no robust effect)",
    "untestable_missing_data": "untestable (missing data)",
    "not_applicable": "not applicable",
    "error": "error",
}


def research_summary_markdown(run_dir: Path) -> str:
    run_dir = Path(run_dir)
    summary = json.loads((run_dir / "summary.json").read_text())
    man = summary["manifest"]
    lb = pd.DataFrame(summary["leaderboard"])
    syn = man.get("is_synthetic")
    lines = [f"# Research Summary - run `{man['run_id']}`", ""]
    if syn:
        world = (man.get("provenance", {}).get("planted_truth") or {}).get("world")
        lines += ["> **SYNTHETIC DATA.** All results below were produced on generated data "
                  f"(world: `{world}`). They validate the research machinery; they are **not** empirical findings "
                  "about SET, SGX or HKEX. Empirical strategy profitability has not been established.", ""]
    lines += [f"- Dataset `{man['dataset']}` (data version `{man['data_version']}`), rules registry `{man['registry_version']}`, "
              f"code `{man['code_version']}`, config `{man['config_file']}` (hash `{man['config_hash']}`).",
              f"- Periods: {man['periods']}. Holdout {'UNLOCKED' if man.get('holdout_unlocked') else 'locked (not evaluated)'}.",
              "- Selection: max discovery-period net Sharpe under the base scenario; frozen in `selection.json`.",
              "- Multiple testing: Benjamini-Hochberg q over every grid point x strategy x market tested in discovery "
              "(one-sided Newey-West test of mean daily net return > 0).",
              "- Verdict rule: *supported* requires BH q < 0.05 in discovery, positive net Sharpe in validation AND OOS, "
              "positive net Sharpe under the conservative scenario, and placebo p <= 0.10.", ""]
    cols = ["strategy", "market", "selected", "verdict", "net_sharpe", "gross_sharpe", "validation_sharpe", "oos_sharpe",
            "conservative_sharpe", "stress_sharpe", "bps_per_trade", "gross_bps_per_trade", "trades", "fill_rate",
            "disc_q_bh", "placebo_p", "capacity"]
    t = lb[[c for c in cols if c in lb]].copy()
    if "verdict" in t:
        t["verdict"] = t["verdict"].map(VERDICT_TEXT).fillna(t["verdict"])
    lines += ["## Leaderboard (base scenario)", "", _md_table(t), ""]
    lines += ["## Hypotheses", ""]
    for sid, cls in STRATEGIES.items():
        sub = lb[lb["strategy"] == sid]
        verdicts = ", ".join(f"{r.market}: {VERDICT_TEXT.get(r.verdict, r.verdict)}" for r in sub.itertuples())
        lines.append(f"- **{sid} {cls.spec.name}** - {verdicts or 'not run'}")
    lines += ["", "On **real** data every hypothesis is currently **untestable**: no licensed SET/SGX/HKEX auction, "
              "indicative, borrow, index-event or futures data is present in this environment.", ""]
    pv = summary.get("pipeline_validation", {})
    if pv.get("applicable"):
        rows = []
        for m, est in (pv.get("estimated") or {}).items():
            for k, v in est.items():
                rows.append(dict(market=m, quantity=k, planted=(pv.get("planted") or {}).get(k), estimated=v))
        lines += ["## Pipeline validation (planted vs recovered)", "",
                  "The generator planted known reversal fractions; the pipeline's estimates from the generated prices:", "",
                  _md_table(pd.DataFrame(rows), "{:.3f}"), ""]
    lines += ["## Distinguishing anomalies from executable strategies", "",
              "For the gap strategies the diagnostic C0->O1 and C0->C1 windows (trade at the closing price) are compared "
              "with the executable O1->C1 window and realised gross / net bps per trade in each study's "
              "`shortfall` block (dashboard section 12). The closing price is not known early enough to trade at it, "
              "except via SGX Trade-at-Close (S07), whose fills are capped by realised TAC volume.", ""]
    tests = pd.DataFrame(summary.get("tests") or [])
    if isinstance(summary.get("tests"), dict) and summary["tests"].get("__frame__"):
        tests = pd.DataFrame(summary["tests"]["records"])
    if len(tests):
        lines += [f"## Multiple testing", "", f"{len(tests)} discovery tests; "
                  f"{int((tests['q_bh'] < 0.05).sum())} with BH q < 0.05; {int((tests['p_holm'] < 0.05).sum())} with Holm p < 0.05 "
                  "(one-sided: mean daily net return > 0).", ""]
    lines += ["## Artefacts", "", "- `dashboard.html` - interactive dashboard", "- `leaderboard.csv`, `multiple_tests.csv`, "
              "`selection.json`, `manifest.json`, `config.yaml`", "- `studies/<S>_<MKT>/` - study.json, daily_<scenario>.parquet, "
              "trades_base.parquet, rejections_base.parquet, intents.parquet", ""]
    return "\n".join(lines)


def write_generated_docs(docs_dir: Path) -> list[Path]:
    docs_dir.mkdir(parents=True, exist_ok=True)
    out = []
    for name, text in (("MARKET_RULES.md", market_rules_markdown()), ("DATA_DICTIONARY.md", data_dictionary_markdown()),
                       ("STRATEGIES.md", strategies_markdown())):
        p = docs_dir / name
        p.write_text(text, encoding="utf-8")
        out.append(p)
    return out
